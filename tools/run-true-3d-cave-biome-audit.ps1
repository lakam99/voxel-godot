        Requirement = "Terrain mesh triangles must be emitted only where the authoritative volume density crosses the solid/air boundary."
        MigrationTarget = "Phase 2/6: build_chunk_mesh must extract a solid/air isosurface from 3D volume samples."
    },
    [pscustomobject]@{
        Id = "terrain-collision-from-mesh-required"
        File = "scripts/MainRuntimeTools.gd"
        Pattern = "create_trimesh_shape|terrain_mesh_create_trimesh_shape|volume_sample_extraction"
        Requirement = "Terrain collision must be built from the same mesh generated by volume extraction."
        MigrationTarget = "Phase 2/6: chunk_assets must use mesh.create_trimesh_shape and runtime chunks must expose matching geometry source metadata."
    }
)

$findings = @()
foreach ($rule in $rules) {
    foreach ($relativePath in $rule.Files) {
        $absolutePath = Join-Path $root $relativePath
        if (-not (Test-Path -LiteralPath $absolutePath)) {
            continue
        }
        $matches = Select-String -LiteralPath $absolutePath -Pattern $rule.Pattern -AllMatches
        foreach ($match in $matches) {
            $findings += [pscustomobject]@{
                ruleId = $rule.Id
                file = $relativePath.Replace("\", "/")
                line = $match.LineNumber
                text = $match.Line.Trim()
                pattern = $rule.Pattern
                requirement = $rule.Requirement
                migrationTarget = $rule.MigrationTarget
            }
        }
    }
}

foreach ($rule in $requiredRules) {
    $absolutePath = Join-Path $root $rule.File
    if (-not (Test-Path -LiteralPath $absolutePath)) {
        $findings += [pscustomobject]@{
            ruleId = $rule.Id
            file = $rule.File.Replace("\", "/")
            line = 0
            text = "missing file"
            pattern = $rule.Pattern
            requirement = $rule.Requirement
            migrationTarget = $rule.MigrationTarget
        }
        continue
    }
    $matches = Select-String -LiteralPath $absolutePath -Pattern $rule.Pattern -AllMatches
    if ($matches.Count -eq 0) {
        $findings += [pscustomobject]@{
            ruleId = $rule.Id
            file = $rule.File.Replace("\", "/")
            line = 0
            text = "required pattern missing"
            pattern = $rule.Pattern
            requirement = $rule.Requirement
            migrationTarget = $rule.MigrationTarget
        }
    }
}

$resolvedReportPath = if ([System.IO.Path]::IsPathRooted($ReportPath)) {
    $ReportPath
} else {
    Join-Path $root $ReportPath
}

$reportDirectory = Split-Path -Parent $resolvedReportPath
if ($reportDirectory -ne "" -and -not (Test-Path -LiteralPath $reportDirectory)) {
    New-Item -ItemType Directory -Force -Path $reportDirectory | Out-Null
}

$status = if ($findings.Count -eq 0) { "passed" } else { "failed" }
$report = [pscustomobject]@{
    schemaVersion = 1
    runnerId = "true_3d_cave_biome_static_audit"
    evidenceLevel = "static-audit"
    status = $status
    failureCount = $findings.Count
    ruleCount = $rules.Count
    requiredRuleCount = $requiredRules.Count
    generatedAtUtc = (Get-Date).ToUniversalTime().ToString("o")
    plan = "CODEX_TRUE_3D_CAVE_BIOME_PLAN.md"
    audit = "CODEX_TRUE_3D_CAVE_BIOME_AUDIT.md"
    findings = $findings
}

$report | ConvertTo-Json -Depth 8 | Set-Content -LiteralPath $resolvedReportPath -Encoding UTF8

if ($findings.Count -gt 0) {
    Write-Host ("true_3d_cave_biome_static_audit failed with {0} findings. Report: {1}" -f $findings.Count, $resolvedReportPath)
    exit 1
}

Write-Host ("true_3d_cave_biome_static_audit passed. Report: {0}" -f $resolvedReportPath)
exit 0
