    [pscustomobject]@{
        Id = "heightfield-terrain-mesh"
        Files = @("scripts/MainPlaytestTools.gd")
        Pattern = "func terrain_surface_height_cell|func terrain_quad_hidden_for_cell|func add_chunk_skirts|func terrain_vertex_local|func terrain_normal_for_cell|surface_quad_hidden_for_cell3|terrain_quad_hidden_for_cell\("
        Requirement = "Terrain mesh must be extracted from authoritative (x,y,z) solid/air samples, not a heightfield with hidden cave quads."
        MigrationTarget = "Phase 2: replace heightfield chunk mesh with volume surface extraction."
    },
    [pscustomobject]@{
        Id = "block-face-terrain-mesh"
        Files = @("scripts/MainPlaytestTools.gd")
        Pattern = "func add_volume_face|func add_volume_quad|directions:\s*Array\[Vector3i\]"
        Requirement = "Terrain must keep the game's natural look; true 3D volume extraction must not regress to visible Minecraft-style cube faces."
        MigrationTarget = "Use continuous density isosurface extraction from the authoritative (x,y,z) sampler."
    },
    [pscustomobject]@{
        Id = "legacy-xz-generation-api"
        Files = @("scripts/MainPropFactory.gd", "scripts/MainInterface.gd")
        Pattern = "func height_at_world|func ground_height_at_world|func terrain_height_cell|func base_height_cell|func natural_base_height_cell|func biome_at_cell|func terrain_material_id_for_cell"
        Requirement = "No authoritative (x,z) terrain, biome, ground, or material generation APIs may remain."
        MigrationTarget = "Phase 1/5: replace callers with 3D samples or temporary adapter-only probes."
    },
    [pscustomobject]@{
        Id = "legacy-xz-generation-call-sites"
        Files = $allScriptFiles
        Pattern = "height_at_world|ground_height_at_world|terrain_height_cell|base_height_cell|natural_base_height_cell|(?<!surface_)\bbiome_at_cell\b|biome_at_cell3|terrain_material_id_for_cell"
        Requirement = "Tests and runtime systems must not call legacy (x,z) terrain, biome, ground, or material APIs."
        MigrationTarget = "Phase 5/6: call surface_y_at_position, ground_y_near_position, surface_y_at_cell(Vector3i), surface_biome_at_cell(Vector3i), or full volume samples."
    },
    [pscustomobject]@{
        Id = "world-generation-height-authority"
        Files = @("scripts/WorldGenerationSystem.gd")
        Pattern = "func surface_height_for_cell3|func edited_surface_height_for_cell3|func base_surface_height_for_cell3|func natural_surface_height_for_cell3|func surface_height_at_world|func surface_height_for_cell"
        Requirement = "World generation must be authoritative as density/solid/air/biome/material samples, with height derived only as a compatibility projection."
        MigrationTarget = "Phase 1: implement sample_cell/sample_world/density_at/solid_at/biome_at/material_at as the authority."
    },
    [pscustomobject]@{
        Id = "external-cave-plan-authority"
        Files = @("scripts/WorldGenerationSystem.gd", "scripts/SubsurfaceSystem.gd", "scripts/StructureSystem.gd")
        Pattern = "register_cave_plan|cave_plan_records|active_plans_from_records|cave_patch_plans|cave_active_plans|cave_records|generated_caves|func cave_plan_for_region|func make_cave_plan"
        Requirement = "Caves must be a biome/density field generated by the world sampler, not external plans placed into terrain."
        MigrationTarget = "Phase 1/3: move cave feature generation into WorldGenerationSystem samples and remove StructureSystem cave authority."
    },
    [pscustomobject]@{
        Id = "cave-mouth-patch-authority"
        Files = @("scripts/WorldGenerationSystem.gd", "scripts/SubsurfaceSystem.gd", "scripts/StructureSystem.gd", "scripts/CaveInteriorBuilder.gd")
        Pattern = "cave_mound_overlay|surface_patch_quad_cut_by_cave_pipe|cave_surface_point_opens_to_air|surface_quad_hidden_for_cell3|terrain_quad_hidden_for_cell|terrain_material_override_for_cell|cave_mouth_portal_cells|cave_terrain_pipe_cut_cells|cave_terrain_opening_cells|cave_mouth_"
        Requirement = "Cave mouth, tunnel, floor, ceiling, wall, terrain cut, mesh, and collision must come from one carved volume, with no mouth-specific patch/portal/rim/facade authority."
        MigrationTarget = "Phase 2/3/4: remove hidden quads, material overrides, and mouth-specific geometry helpers."
    },
    [pscustomobject]@{
        Id = "separate-cave-volume-mesh"
        Files = @("scripts/SubsurfaceSystem.gd", "scripts/CaveInteriorBuilder.gd")
        Pattern = "func rebuild_cave_patch|func build_cave_volume_mesh|func add_cave_volume_to_surface_tool|func add_cave_voxel_volume_to_surface_tool|func add_cave_surface_shell_to_surface_tool|SubsurfaceCaveVisual|SubsurfaceCaveBody|SubsurfaceCaveCollision|func build_visual_mesh|func build_collision_mesh|func add_carved_volume|rendered_shell_"
        Requirement = "Cave mesh and collision must be emitted by the same chunk volume extraction path as terrain, not by a separate cave shell/body."
        MigrationTarget = "Phase 2/4: delete separate cave shell/volume authority; keep only decoration helpers after volume exists."
    },
    [pscustomobject]@{
        Id = "structure-system-cave-builder"
        Files = $allScriptFiles
        Pattern = "build_cave|apply_cave_terrain_edits|cave_plan_for_region|cave_records_snapshot|find_cave_plan_sample|cave_terrain_mouth_summary|hiddenPortalCells|stoneOverridePortalCells|terrain_material_override_for_cell"
        Requirement = "StructureSystem and tests must not create or accept caves as placed structures, hidden portals, or material override patches."
        MigrationTarget = "Phase 3/6: query cave biome volumes, decorate after discovery, and fail tests on banned architecture."
    },
    [pscustomobject]@{
        Id = "height-edit-authority"
        Files = @("scripts/MainCore.gd", "scripts/MainSaveState.gd", "scripts/PlaytestRunner.gd", "scripts/testing/CaveGenerationTestRunner.gd", "scripts/testing/CaveVisualPlaytestRunner.gd", "scripts/visual/VisualCaptureRunner.gd")
