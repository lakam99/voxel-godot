$requiredRules = @(
    [pscustomobject]@{
        Id = "terrain-mesh-volume-sample-required"
        File = "scripts/MainPlaytestTools.gd"
        Pattern = "sample_world|density_at"
        Requirement = "Chunk terrain mesh generation must sample the authoritative (x,y,z) volume."
        MigrationTarget = "Phase 2: build_chunk_mesh must extract surfaces from WorldGenerationSystem density/sample queries."
    },
    [pscustomobject]@{
        Id = "world-generation-sample-api-required"
        File = "scripts/WorldGenerationSystem.gd"
        Pattern = "func sample_cell|func sample_world|func density_at|func solid_at|func biome_at|func material_at"
        Requirement = "WorldGenerationSystem must expose the required authoritative 3D sample API."
        MigrationTarget = "Phase 1: keep sample_cell/sample_world/density_at/solid_at/biome_at/material_at as the generation authority."
    },
    [pscustomobject]@{
        Id = "surface-projection-volume-scan-required"
        File = "scripts/WorldGenerationSystem.gd"
        Pattern = "func volume_surface_y_for_cell|sample_cell\(Vector3i\(cell.x, y, cell.z\)\)"
        Requirement = "Surface projection helpers must scan authoritative (x,y,z) solid/air samples."
        MigrationTarget = "Phase 5: derive surface_y_for_cell from volume_surface_y_for_cell."
    },
    [pscustomobject]@{
        Id = "terrain-mesh-solid-air-transition-required"
        File = "scripts/MainPlaytestTools.gd"
